#!/usr/bin/env python3
"""Extract The Ancient Art of War at Sea graphics from the original 3.5" disk files.

Generated by Claude Opus 5.5
Guided by Brett Hallen, Nov 2026

Run from anywhere:  python3 extract_graphics.py
Needs Pillow (pip install pillow). Reads ../WAS_Original_Files_3.5 and
writes PNGs into the CGA/ and VGA/ folders next to this script.

CGA (WAS.EXE):
  SM         94 map tiles, 2 bits per pixel (same layout as WAR's M)
  SP*, B, AD full-screen pictures: two fields (even lines, then odd lines),
             each = word N, then N codes; code c <= 200 repeats the next
             byte c times, c > 200 copies the next c - 200 bytes
             (load_picture ovl1:CBEA in WAS.EXE)
  WAS.EXE never changes the CGA palette for these pictures: they show in
  the BIOS default for mode 4, palette 1 high intensity (black, cyan,
  magenta, white).
EGA / Tandy 16-colour (WAST.EXE):
  WAST.DAT   archive in the same format as WARET.DAT (see
             WAR_Analysis/WAR_file_reference.md): 16-colour pictures and map
             tiles, copies of the text files. Unlike WARET.DAT the pictures
             carry no palette: they use the standard 16-colour palette.
"""
import os
import struct
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'WAS_Original_Files_3.5')
CGA_DIR = os.path.join(HERE, 'CGA')
VGA_DIR = os.path.join(HERE, 'VGA')

# CGA palette 1, high intensity: black, cyan, magenta, white
CGA_PALETTE = [(0, 0, 0), (85, 255, 255), (255, 85, 255), (255, 255, 255)]
# the standard 16 colours (CGA/EGA/Tandy), used by every WAST.DAT picture
EGA_PALETTE = [(0, 0, 0), (0, 0, 170), (0, 170, 0), (0, 170, 170),
               (170, 0, 0), (170, 0, 170), (170, 85, 0), (170, 170, 170),
               (85, 85, 85), (85, 85, 255), (85, 255, 85), (85, 255, 255),
               (255, 85, 85), (255, 85, 255), (255, 255, 85), (255, 255, 255)]

CGA_PICTURES = {
    'SPM': 'title', 'SPI': 'title_ship', 'SPE': 'scroll_1', 'SPF': 'scroll_2',
    'SPJ': 'opponents', 'SPG': 'scenes_1', 'SPH': 'scenes_2',
    'SPK': 'options_shoppe', 'SPN': 'battle_report_1', 'SPO': 'battle_report_2',
    'SPP': 'battle_report_3', 'SPQ': 'battle_report_4',
    'AD': 'opponent_face', 'B': 'boarding_deck',
}

VGA_PICTURES = {
    1: 'SPM_title', 2: 'SPI_title_ship', 3: 'SPE_scroll_1', 4: 'SPF_scroll_2',
    5: 'SPJ_opponents', 6: 'SPG_scenes_1', 7: 'SPH_scenes_2',
    8: 'SPK_options_shoppe', 9: 'SPO_battle_report_2', 10: 'SPN_battle_report_1',
    13: 'AD_opponent_face', 29: 'B_boarding_deck',
}
VGA_TILE_RECORDS = (30, 31)        # 90 + 4 tiles


def read(name):
    with open(os.path.join(SRC, name), 'rb') as f:
        return f.read()


# ---------------------------------------------------------------- drawing
def draw_2bpp(data, width_bytes, rows, row_offset):
    im = Image.new('RGB', (width_bytes * 4, rows))
    px = im.load()
    for y in range(rows):
        base = row_offset(y)
        for xb in range(width_bytes):
            v = data[base + xb]
            for p in range(4):
                px[xb * 4 + p, y] = CGA_PALETTE[(v >> (6 - 2 * p)) & 3]
    return im


def draw_4bpp(data, width, height, bytes_per_row, palette):
    im = Image.new('RGB', (width, height))
    px = im.load()
    for y in range(height):
        for x in range(width):
            b = data[y * bytes_per_row + x // 2]
            px[x, y] = palette[(b >> 4) if x % 2 == 0 else (b & 15)]
    return im


def tile_sheet(tiles, path, per_row=12, scale=3):
    w, h = tiles[0].size
    rows = (len(tiles) + per_row - 1) // per_row
    sheet = Image.new('RGB', (per_row * (w + 2), rows * (h + 2)), (60, 60, 60))
    for k, t in enumerate(tiles):
        sheet.paste(t, ((k % per_row) * (w + 2), (k // per_row) * (h + 2)))
    sheet.resize((sheet.width * scale, sheet.height * scale), Image.NEAREST).save(path)


def contact_sheet(items, path, per_row=3):
    rows = (len(items) + per_row - 1) // per_row
    sheet = Image.new('RGB', (per_row * 330, rows * 218), (40, 40, 40))
    draw = ImageDraw.Draw(sheet)
    for k, (label, im) in enumerate(items):
        x, y = (k % per_row) * 330, (k // per_row) * 218
        sheet.paste(im, (x + 5, y + 14))
        draw.text((x + 5, y + 2), label, fill=(255, 255, 0))
    sheet.save(path)


def save_tiles(tiles, folder, prefix):
    os.makedirs(folder, exist_ok=True)
    for k, t in enumerate(tiles):
        # tile number k+1 is what a campaign map stores
        t.save(os.path.join(folder, f'{prefix}_{k + 1:02d}.png'))


# ---------------------------------------------------------------- CGA
def cga_tiles():
    """SM: records of [word width-in-words, word height/2, pixels]."""
    d = read('SM')
    tiles, i = [], 0
    while i < len(d):
        w, h = struct.unpack('<HH', d[i:i + 4])
        i += 4
        bpr, rows = w * 2, h * 2
        tiles.append(draw_2bpp(d[i:i + bpr * rows], bpr, rows, lambda y, b=bpr: y * b))
        i += bpr * rows
    return tiles


def cga_picture(name):
    """Two fields; each = word N, then N codes (<= 200 run, > 200 literal)."""
    d = read(name)
    out, pos = bytearray(), 0
    for _ in range(2):
        n = d[pos] | d[pos + 1] << 8
        pos += 2
        field = bytearray()
        for _ in range(n):
            c = d[pos]
            pos += 1
            if c <= 200:
                field += bytes([d[pos]]) * c
                pos += 1
            else:
                field += d[pos:pos + c - 200]
                pos += c - 200
        assert len(field) == 8000, f'{name}: field of {len(field)} bytes'
        out += field
    # even lines in the first 8000 bytes, odd lines in the second
    return draw_2bpp(out, 80, 200, lambda y: (y % 2) * 8000 + (y // 2) * 80)


# ---------------------------------------------------------------- 16 colours
def wast_records():
    d = read('WAST.DAT')
    table = struct.unpack('<I', d[:4])[0]
    count = d[table + 3] | d[table + 4] << 8
    entries = [struct.unpack('<HI', d[table + 5 + k * 6:table + 11 + k * 6]) for k in range(count)]
    records = {}
    for rec_id, off in entries:
        length, checksum = d[off] | d[off + 1] << 8, d[off + 2]
        payload = d[off + 3:off + 3 + length]
        assert sum(payload) & 255 == checksum, f'checksum error in record {rec_id}'
        records[rec_id] = payload
    return records


def unpack(src, size):
    """Signed n; n >= 0 copy n+1 bytes, n < 0 repeat next byte -n times."""
    out, i = bytearray(), 0
    while len(out) < size:
        n = src[i]
        i += 1
        if n < 128:
            out += src[i:i + n + 1]
            i += n + 1
        else:
            out += bytes([src[i]]) * (256 - n)
            i += 1
    return bytes(out[:size])


def unpack_record(payload):
    """Word unpacked size, run-length data (no palette in WAST.DAT)."""
    return unpack(payload[2:], payload[0] | payload[1] << 8)


def vga_picture(payload):
    raw = unpack_record(payload)
    w, h, bpr = struct.unpack('<HHH', raw[:6])
    return draw_4bpp(raw[6:], w, h, bpr, EGA_PALETTE)


def vga_tiles(payload):
    raw = unpack_record(payload)
    tiles, i = [], 0
    while i + 4 <= len(raw):
        w, h = struct.unpack('<HH', raw[i:i + 4])
        i += 4
        bpr, rows = w * 2, h * 2
        tiles.append(draw_4bpp(raw[i:i + bpr * rows], bpr * 2, rows, bpr, EGA_PALETTE))
        i += bpr * rows
    return tiles


# ---------------------------------------------------------------- main
def main():
    os.makedirs(CGA_DIR, exist_ok=True)
    os.makedirs(VGA_DIR, exist_ok=True)

    tiles = cga_tiles()
    save_tiles(tiles, os.path.join(CGA_DIR, 'tiles'), 'SM')
    tile_sheet(tiles, os.path.join(CGA_DIR, 'WAS_SM_map_tiles.png'))
    items = []
    for name, label in CGA_PICTURES.items():
        im = cga_picture(name)
        im.save(os.path.join(CGA_DIR, f'{name}_{label}.png'))
        items.append((name, im))
    contact_sheet(items, os.path.join(CGA_DIR, 'WAS_CGA_pictures.png'))
    print(f'CGA: {len(tiles)} tiles, {len(items)} pictures')

    records = wast_records()
    tiles = []
    for rec_id in VGA_TILE_RECORDS:
        tiles += vga_tiles(records[rec_id])
    save_tiles(tiles, os.path.join(VGA_DIR, 'tiles'), 'tile')
    tile_sheet(tiles, os.path.join(VGA_DIR, 'WAS_16colour_map_tiles.png'))
    items = []
    for rec_id, label in VGA_PICTURES.items():
        im = vga_picture(records[rec_id])
        im.save(os.path.join(VGA_DIR, f'rec{rec_id:02d}_{label}.png'))
        items.append((f'rec {rec_id}: {label}', im))
    contact_sheet(items, os.path.join(VGA_DIR, 'WAS_16colour_pictures.png'))
    print(f'16 colours: {len(tiles)} tiles, {len(items)} pictures')


if __name__ == '__main__':
    main()
