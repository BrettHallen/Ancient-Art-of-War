void screen_to_composite(const Screen *s, bool new_cga, uint32_t *out)
{
    /* the palette WAR.EXE chose: 0 (green, red, yellow) on the scrolls, else 1 */
    int pal1 = !(s->pal[1].r == 0x55 && s->pal[1].g == 0xFF && s->pal[1].b == 0x55);
    bool known = (s->pal[0].r | s->pal[0].g | s->pal[0].b) == 0 && s->pal[1].r == 0x55 && s->pal[1].g == 0xFF &&
                 s->pal[3].r == 0xFF && s->pal[3].g == 0xFF;   /* not the greys of a black-and-white display */
    if (!known) {   /* not a CGA palette (the Options Shoppe's black/white): each pixel twice */
        static uint32_t line[SCREEN_W * SCREEN_H];
        screen_to_xrgb(s, line);
        for (int i = 0; i < SCREEN_W * SCREEN_H; i++) out[2 * i] = out[2 * i + 1] = line[i];
        return;
    }
    const uint32_t (*t)[64] = COMPOSITE[new_cga][pal1];
    for (int y = 0; y < SCREEN_H; y++) {
        const uint8_t *p = &s->px[y * SCREEN_W];
        uint32_t *o = &out[y * COMP_W];
        for (int x = 0; x < COMP_W; x++) {
            int i = x >> 1;
            int l = i > 0 ? p[i - 1] & 3 : 0, m = p[i] & 3, r = i < SCREEN_W - 1 ? p[i + 1] & 3 : 0;
            o[x] = 0xFF000000u | t[x & 3][l * 16 + m * 4 + r];
        }
    }
}
